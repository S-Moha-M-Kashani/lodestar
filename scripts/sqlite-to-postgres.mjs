// scripts/sqlite-to-postgres.mjs — move the two SQLite records into Postgres.
//
// One-time, and safe to run twice: every insert is ON CONFLICT DO NOTHING, so
// a second run reports zeros rather than doubling the board. It reads the
// column list from SQLite at runtime instead of naming columns here, because
// this file must not become a third place the schema is written down —
// scripts/postgres/001-schema.sql and server.js are already two.
//
// Soft-deleted rows travel too. They are the Trash, and a migration that
// dropped them would quietly destroy the only copy of everything the user had
// deleted but not purged — which the durability promise forbids.
import { DatabaseSync } from 'node:sqlite';
import pg from 'pg';

const TABLES = [
  ['board', 'boards', ['id']],
  ['board', 'cards', ['id']],
  ['board', 'card_edits', ['id']],
  ['board', 'categories', ['board_id', 'id']],
  ['assistant', 'sessions', ['id']],
  ['assistant', 'messages', ['id']],
];

async function copyTable(sqlite, client, schema, table, keyCols) {
  const cols = sqlite.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);
  const rows = sqlite.prepare(`SELECT * FROM ${table}`).all();
  if (rows.length === 0) return 0;
  const placeholders = cols.map((_, i) => `$${i + 1}`).join(', ');
  const sql = `INSERT INTO ${schema}.${table} (${cols.join(', ')}) ` +
    `VALUES (${placeholders}) ON CONFLICT (${keyCols.join(', ')}) DO NOTHING`;
  let added = 0;
  for (const row of rows) {
    const r = await client.query(sql, cols.map((c) => row[c]));
    added += r.rowCount;
  }
  return added;
}

/** Copy both SQLite records into Postgres. Returns rows added per table. */
export async function migrate({ boardDb, assistantDb, pgUrl, schemas = {} }) {
  const board = schemas.board || 'board';
  const assistant = schemas.assistant || 'assistant';
  const client = new pg.Client({ connectionString: pgUrl });
  await client.connect();
  const added = {};
  try {
    await client.query('BEGIN');
    for (const [group, table, keyCols] of TABLES) {
      const file = group === 'board' ? boardDb : assistantDb;
      const schema = group === 'board' ? board : assistant;
      const sqlite = new DatabaseSync(file, { readOnly: true });
      try {
        added[`${schema}.${table}`] = await copyTable(sqlite, client, schema, table, keyCols);
      } finally {
        sqlite.close();
      }
    }
    // messages.id is GENERATED BY DEFAULT AS IDENTITY, so explicit ids do not
    // advance the sequence. Left alone, the next insert reuses id 1 and fails
    // on the primary key — the migration would look clean and break the first
    // chat message afterwards.
    await client.query(
      `SELECT setval(pg_get_serial_sequence('${assistant}.messages', 'id'),
                     COALESCE((SELECT MAX(id) FROM ${assistant}.messages), 1))`);
    await client.query('COMMIT');
    return added;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    await client.end();
  }
}
